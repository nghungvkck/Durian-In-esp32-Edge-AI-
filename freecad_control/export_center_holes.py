"""Export the accepted CAD directly, without any old trial scripts.

Run only when artifact updates are requested: writes into the final 3D folder.
"""
from pathlib import Path
import FreeCAD as App
import FreeCADGui as Gui
import json
import Part, MeshPart, Mesh
ROOT=Path(r'D:\Hoc_tap_Sinh_Vien\Kien_thu_AI\Project\Duration_edge_ai')
OUT=ROOT/'3D/Enclosure_USB_Near_Wall_D50'
Gui.Selection.clearSelection()
if hasattr(Gui.Selection,'removePreselection'): Gui.Selection.removePreselection()
namespace={'__name__':'__freecad_validation__','check_stl':False}
p=ROOT/'freecad_control/validate_latest.py'
exec(compile(p.read_text(encoding='utf-8'),str(p),'exec'),namespace)
report=namespace['result']; doc=namespace['doc']
assert report['passed']
printed=[doc.Rear_half,doc.Front_half]
(OUT/'STL').mkdir(exist_ok=True)
for o in printed:
    target=OUT/'STL'/(o.Name+'.stl')
    MeshPart.meshFromShape(Shape=o.Shape,LinearDeflection=.06,AngularDeflection=.16,Relative=False).write(str(target))
    mesh=Mesh.Mesh(str(target)); assert mesh.isSolid()
    report['printed_parts'][o.Name]['stl_facets']=mesh.CountFacets
    report['printed_parts'][o.Name]['stl_closed']=True
report['stl_checked']=True
Part.export(printed,str(OUT/'Two_shell_halves.step'))
Part.export([doc.getObject(n) for n in ('Mic_PCB','Mic_ICS43434','Mic_Pads','Mic_Passives')],str(OUT/'ICS43434_upright_reference.step'))
Part.export([o for o in doc.Objects if o.Name.startswith('Key_') and 'Screw' not in o.Name],str(OUT/'Three_button_module_placed.step'))
App.setActiveDocument(doc.Name)
def view(direction):
    n=App.Vector(*direction); n.normalize()
    right=App.Vector(0,0,1).cross(n); right.normalize(); up=n.cross(right)
    v=Gui.activeDocument().activeView()
    v.setCameraOrientation(App.Rotation(right,up,n,'ZXY').Q); v.fitAll(); return v
doc.Front_half.Visibility=True
view((.4,1,.12)).saveImage(str(OUT/'closed_center_holes.png'),1200,1800,'White')
view((.7,-1,.4)).saveImage(str(OUT/'rear_sound_holes.png'),1200,1800,'White')
doc.Front_half.Visibility=False; doc.Rear_half.Visibility=True
view((.65,1,.12)).saveImage(str(OUT/'center_holes_inside.png'),1200,1800,'White')
doc.Front_half.Visibility=True
v=view((0,1,0)); v.setCameraType('Orthographic'); v.fitAll()
v.saveImage(str(OUT/'front_center_holes.png'),1200,1800,'White')
camera=v.getCameraNode()
camera.position.setValue(0,120,186); camera.height.setValue(42); camera.focalDistance.setValue(120)
v.saveImage(str(OUT/'center_holes_detail.png'),1400,1000,'White')
view((-.65,1,.1)).saveImage(str(OUT/'three_seam_screws.png'),1200,1800,'White')
v.viewTop(); v.fitAll()
v.saveImage(str(OUT/'center_slot_top.png'),1200,1000,'White')
v.viewBottom(); v.fitAll()
v.saveImage(str(OUT/'switch_bottom.png'),1200,1000,'White')
view((.55,1,.7)).saveImage(str(OUT/'center_slot_closed.png'),1200,1800,'White')
doc.Front_half.Visibility=False
view((.65,1,.35)).saveImage(str(OUT/'center_slot_inside.png'),1200,1800,'White')
doc.recompute(); doc.save()
report['notes'][0]='Generated by export_center_holes.py after validation.'
(OUT/'validation.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
result={'file':doc.FileName,'both_stl_closed':True,'hole_axis':'Y','center_x_mm':0,'hole_diameter_mm':4,'pitch_mm':20,'old_side_holes_closed':True,'detail':str(OUT/'center_holes_detail.png')}
